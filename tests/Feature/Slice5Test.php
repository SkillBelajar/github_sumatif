<?php

namespace Tests\Feature;

use App\Models\AssessmentSession;
use App\Models\LearningObjective;
use App\Models\Question;
use App\Models\Subject;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class Slice5Test extends TestCase
{
    use RefreshDatabase;

    private function teacher(): User
    {
        return User::create([
            'name' => 'Guru Test',
            'email' => 'guru'.uniqid().'@test.local',
            'password' => 'password',
            'role' => 'teacher',
            'school_name' => 'Sekolah Test',
            'email_verified_at' => now(),
        ]);
    }

    private function question(array $overrides = []): Question
    {
        $subject = Subject::create(['name' => 'Matematika', 'code' => 'MAT']);
        $lo = LearningObjective::create([
            'subject_id' => $subject->id,
            'name' => 'Operasi hitung bilangan bulat',
            'kktp_rubric' => [['level' => 'Baik', 'min_score' => 80, 'criteria' => 'Tepat']],
        ]);

        return Question::create(array_merge([
            'learning_objective_id' => $lo->id,
            'phase' => 'Fase D',
            'type' => 'multiple_choice',
            'content' => 'Berapakah 2 + 2?',
            'options' => ['A' => '3', 'B' => '4', 'C' => '5', 'D' => '6'],
            'correct_answer' => 'B',
        ], $overrides));
    }

    private function makeSession(User $teacher): AssessmentSession
    {
        return AssessmentSession::create([
            'user_id' => $teacher->id,
            'name' => 'Sumatif Tengah Semester',
            'duration_minutes' => 45,
            'token' => AssessmentSession::generateToken(),
            'status' => 'draft',
        ]);
    }

    public function test_teacher_can_create_session_with_autogenerated_token(): void
    {
        $teacher = $this->teacher();

        $this->actingAs($teacher)
            ->post('/teacher/assessments', [
                'name' => 'Sumatif Tengah Semester Ganjil',
                'duration_minutes' => 90,
                'classroom_ids' => ['VII-A', 'VII-B'],
            ])
            ->assertRedirect();

        $session = AssessmentSession::firstOrFail();
        $this->assertSame($teacher->id, $session->user_id);
        $this->assertSame('draft', $session->status);
        $this->assertSame(90, $session->duration_minutes);
        $this->assertMatchesRegularExpression('/^[A-Z0-9]{6}$/', $session->token);
        $this->assertCount(2, $session->classrooms);
        $this->assertSame(['VII-A', 'VII-B'], $session->classrooms->pluck('name')->sort()->values()->all());
    }

    public function test_token_must_be_unique(): void
    {
        $teacher = $this->teacher();
        $this->makeSession($teacher);

        $this->actingAs($teacher)
            ->post('/teacher/assessments', [
                'name' => 'Sesi Kedua',
                'duration_minutes' => 30,
                'token' => AssessmentSession::first()->token,
            ])
            ->assertSessionHasErrors('token');

        $this->assertSame(1, AssessmentSession::count());
    }

    public function test_token_rejected_if_not_alphanumeric(): void
    {
        $teacher = $this->teacher();

        $this->actingAs($teacher)
            ->post('/teacher/assessments', [
                'name' => 'Sesi Kustom',
                'duration_minutes' => 30,
                'token' => 'ABC-123',
            ])
            ->assertSessionHasErrors('token');
    }

    public function test_teacher_can_sync_questions_to_session(): void
    {
        $teacher = $this->teacher();
        $questions = $this->question()->pluck('id');
        $this->question(['content' => 'Soal kedua']);
        $session = $this->makeSession($teacher);

        $this->actingAs($teacher)
            ->post('/teacher/assessments/'.$session->id.'/questions', ['question_ids' => [$questions[0]]])
            ->assertRedirect();

        $this->assertSame(1, $session->fresh()->questions()->count());
    }

    public function test_activate_blocked_when_session_has_no_questions(): void
    {
        $teacher = $this->teacher();
        $session = $this->makeSession($teacher);

        $this->actingAs($teacher)
            ->post('/teacher/assessments/'.$session->id.'/activate')
            ->assertRedirect()
            ->assertSessionHas('error');

        $this->assertSame('draft', $session->fresh()->status);
    }

    public function test_activate_succeeds_when_session_has_questions(): void
    {
        $teacher = $this->teacher();
        $session = $this->makeSession($teacher);
        $session->questions()->attach($this->question()->id);

        $this->actingAs($teacher)
            ->post('/teacher/assessments/'.$session->id.'/activate')
            ->assertRedirect()
            ->assertSessionHas('success');

        $this->assertSame('active', $session->fresh()->status);
    }

    public function test_teacher_cannot_access_other_teachers_session(): void
    {
        $owner = $this->teacher();
        $session = $this->makeSession($owner);
        $other = $this->teacher();

        $this->actingAs($other)
            ->put('/teacher/assessments/'.$session->id, ['name' => 'Hack', 'duration_minutes' => 1])
            ->assertForbidden();
    }

    public function test_question_page_filters_by_subject(): void
    {
        $teacher = $this->teacher();
        $session = $this->makeSession($teacher);
        $question = $this->question();

        $this->actingAs($teacher)
            ->get('/teacher/assessments/'.$session->id.'/questions?subject_id='.$question->learningObjective->subject_id)
            ->assertOk()
            ->assertInertia(fn ($page) => $page->component('Teacher/AssessmentSessions/Questions', false));
    }
}
